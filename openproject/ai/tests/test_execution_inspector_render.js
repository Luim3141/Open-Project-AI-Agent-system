// Exercise the actual Run Inspector renderer without a browser or a live service.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../core/overlay/app/views/qldapm_ai/_engineering_command_center.html.erb'),'utf8');
const start=source.includes('  function escapeQccHtml(')?source.indexOf('  function escapeQccHtml('):source.indexOf('  function renderExecutionData(');
const end=source.indexOf('  // Modal Escape key support',start);
assert(start>=0 && end>start);
const elements={};
const document={getElementById(id){return elements[id]||(elements[id]={textContent:'',innerHTML:'',className:''});}};
const context=vm.createContext({document,formatVNDateTime:()=>'-'});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../core/overlay/app/views/qldapm_ai/_engineering_owner_ux_script.html.erb'),'utf8'),context);
vm.runInContext(source.slice(start,end),context);
const attack='<img src=x onerror=alert(1)>';
context.renderExecutionData({state:'FAILED',final_output:attack,nodes:[{agent:'dev',name:attack,objective:attack,output:attack,state:'FAILED'}],events:[{agent_id:attack,event_type:attack,status:'FAILED'}]});
assert(!elements['qcc-dag-container'].innerHTML.includes(attack),'DAG contains executable markup');
assert(!elements['qcc-events-tbody'].innerHTML.includes(attack),'event contains executable markup');
assert(elements['qcc-dag-container'].innerHTML.includes('&lt;img'));
context.renderExecutionData({});
assert.equal(elements['qcc-run-modal-status-badge'].textContent,'UNKNOWN');
assert.equal(elements['qcc-run-metric-tokens'].textContent,'Chưa có dữ liệu');
assert.equal(elements['qcc-run-metric-calls'].textContent,'Chưa có dữ liệu');
assert.equal(elements['qcc-run-metric-agents'].textContent,'Chưa có dữ liệu');
context.renderExecutionData({state:'RUNNING',metrics:{tokens:0,calls:0},nodes:[],events:[{timestamp:'not-a-date',sequence:attack,status:attack}]});
assert.equal(elements['qcc-run-metric-tokens'].textContent,'0');
assert.equal(elements['qcc-run-metric-calls'].textContent,'0 calls');
assert.equal(elements['qcc-run-metric-agents'].textContent,'0 Agents');
assert(!elements['qcc-events-tbody'].innerHTML.includes(attack));
const toastContainer={appendChild(node){this.child=node;}};
const toastDocument={getElementById(){return toastContainer;},createElement(){return {setAttribute(){},style:{},innerHTML:''};}};
const toastCtx=vm.createContext({document:toastDocument,setTimeout(){},escapeQccHtml:context.escapeQccHtml});
const toastStart=source.indexOf('  function showClientToast('),toastEnd=source.indexOf('  function resetSubmittingButtons(',toastStart);
vm.runInContext(source.slice(toastStart,toastEnd),toastCtx);
toastCtx.showClientToast('error',attack,attack);
assert(!toastContainer.child.innerHTML.includes(attack),'toast contains executable markup');
assert(!source.includes('19/19 Tests Pass'));
assert(!source.includes('5 PRs Hoạt động'));
const pipeline=source.split('<!-- TAB 2: PIPELINE 8 GIAI ĐOẠN -->')[1].split('<!-- TAB 3: AGENT WORKFORCE -->')[0];
for(const label of ['>Đã giao<','>Bảo đảm<','>Phê duyệt<','>Sẵn sàng<']) assert(!pipeline.includes(label),'pipeline claims an unverified stage');
console.log('PASS inspector escaping and missing-state contracts; no browser');
